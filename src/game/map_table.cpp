int zelda64::map_count() {
    return static_cast<int>(map_entrance_counts.size());
}

int zelda64::submap_count(int map) {
    if (map < 0 || map >= map_count()) {
        return 0;
    }
    return static_cast<int>(map_entrance_counts[map].size());
}

int zelda64::entrance_count(int map, int submap) {
    if (submap < 0 || submap >= submap_count(map)) {
        return 0;
    }
    return map_entrance_counts[map][submap];
}

