std::string zelda64::submap_label(int map, int submap) {
    std::vector<std::string> destinations;
    bool has_local_exits = false;
    for (const Exit& exit : exits) {
        if (exit.src_map != map || exit.src_submap != submap) {
            continue;
        }
        if (exit.dst_map == map) {
            has_local_exits = true;
        }
        else {
            append_unique(destinations, map_name(exit.dst_map));
        }
    }

    std::string label = std::to_string(submap);
    if (!destinations.empty()) {
        label += ": to " + join(destinations);
    }
    else if (has_local_exits) {
        label += ": interior";
    }
    return label;
}

std::string zelda64::entrance_label(int map, int submap, int entrance) {
    std::vector<std::string> sources;
    for (const Exit& exit : exits) {
        if (exit.dst_map != map || exit.dst_submap != submap || exit.dst_entrance != entrance) {
            continue;
        }
        if (exit.src_map == map) {
            append_unique(sources, "submap " + std::to_string(exit.src_submap));
        }
        else {
            append_unique(sources, map_name(exit.src_map));
        }
    }

    std::string label = std::to_string(entrance);
    if (!sources.empty()) {
        label += ": from " + join(sources);
    }
    return label;
}
